"""Coverage-safe on-policy distillation with MRPO grouped GUI rollouts.

A documentation section is validated only after all linked tasks have been
teacher-reviewed on every selected profile and a checkpoint has been written.
The policy update uses Mobile-Agent-v3.5-style oversample/select groups: all
candidate trajectories are generated by one frozen current policy, collapsed
subgroups are repaired from the same on-policy pool when possible, and fully
collapsed pools contribute supervised losses but no policy-gradient advantage.
"""
from __future__ import annotations

import random
from collections import defaultdict
from dataclasses import dataclass
from typing import Callable, Sequence

import numpy as np

from .distillation import (
    DistillationMetrics,
    DistillationSample,
    EmulatorEnvironment,
    OnPolicyConfig,
    PolicyUpdater,
    RolloutObservation,
    StudentPolicy,
    TeacherEvaluator,
)
from .document_curriculum import CoverageLedger, CoverageStatus, CurriculumTask
from .emulator_lab import EmulatorMatrix, EmulatorProfile
from .mrpo import (
    completed_prefix_length,
    group_relative_advantages,
    last_checkpoint_step,
    route_from_task,
    select_training_group,
)


@dataclass(frozen=True)
class _Trajectory:
    rows: tuple[tuple[object, object, object, object, float], ...]
    observations: tuple[RolloutObservation, ...]
    terminal_success: bool
    completed_prefix: int


class OnPolicyDistiller:
    """Collect and immediately optimize grouped current-policy trajectories."""

    def __init__(
        self,
        student: StudentPolicy,
        teacher: TeacherEvaluator,
        updater: PolicyUpdater,
        environment_factory: Callable[[EmulatorProfile], EmulatorEnvironment],
        config: OnPolicyConfig | None = None,
        coverage: CoverageLedger | None = None,
        *,
        group_size: int = 2,
        oversample_factor: int = 2,
        checkpoint_reward_weight: float = 0.5,
    ) -> None:
        self.student = student
        self.teacher = teacher
        self.updater = updater
        self.environment_factory = environment_factory
        self.config = config or OnPolicyConfig()
        self.coverage = coverage
        self.group_size = int(group_size)
        self.oversample_factor = int(oversample_factor)
        self.checkpoint_reward_weight = float(checkpoint_reward_weight)
        if self.group_size < 2:
            raise ValueError("group_size must be at least 2")
        if self.oversample_factor < 1:
            raise ValueError("oversample_factor must be positive")
        if self.checkpoint_reward_weight < 0:
            raise ValueError("checkpoint_reward_weight must be non-negative")
        self._rng = random.Random(self.config.seed)

    def train(
        self, tasks: Sequence[CurriculumTask], matrix: EmulatorMatrix
    ) -> DistillationMetrics:
        if not tasks:
            return DistillationMetrics(0, 0, 0, 0.0, 0.0, None)

        pending: list[DistillationSample] = []
        rewards: list[float] = []
        scores: list[float] = []
        verified = updates = 0
        checkpoint: str | None = None
        task_profiles: dict[str, set[str]] = defaultdict(set)
        reviewed_task_profiles: set[tuple[str, str]] = set()

        for profile in tuple(matrix.profiles):
            profile_tasks = [task for task in tasks if task.os_family == profile.os_family]
            for task in profile_tasks:
                task_profiles[task.task_id].add(profile.profile_id)
                route = route_from_task(task)
                frozen_version = int(self.student.policy_version)
                pool = [
                    self._rollout(task, profile, route)
                    for _ in range(self.group_size * self.oversample_factor)
                ]
                if int(self.student.policy_version) != frozen_version:
                    raise RuntimeError(
                        "student policy changed while collecting an MRPO on-policy pool"
                    )

                for trajectory in pool:
                    for _, _, outcome, judgement, reward in trajectory.rows:
                        rewards.append(float(reward))
                        scores.append(float(judgement.total_score))
                        verified += int(outcome.verified)
                        reviewed_task_profiles.add((task.task_id, profile.profile_id))
                        self._mark_review(task, profile, judgement.teacher_id)

                selection = select_training_group(
                    [trajectory.terminal_success for trajectory in pool],
                    self.group_size,
                    self._rng,
                )
                selected = [pool[index] for index in selection.indices]
                group_advantages = (
                    group_relative_advantages(
                        [trajectory.terminal_success for trajectory in selected]
                    )
                    if selection.informative
                    else tuple(0.0 for _ in selected)
                )

                for trajectory, group_advantage in zip(selected, group_advantages):
                    rows, policy_enabled = self._training_rows(trajectory, route)
                    step_advantages = self._advantages([row[4] for row in rows])
                    for row, step_advantage in zip(rows, step_advantages):
                        observation, proposal, outcome, judgement, reward = row
                        advantage = 0.0
                        if policy_enabled and selection.informative:
                            advantage = float(
                                np.clip(
                                    group_advantage + 0.25 * step_advantage,
                                    -self.config.advantage_clip,
                                    self.config.advantage_clip,
                                )
                            )
                        pending.append(
                            DistillationSample(
                                task,
                                profile,
                                observation,
                                proposal,
                                outcome,
                                judgement,
                                float(reward),
                                advantage,
                            )
                        )

                if len(pending) >= self.config.rollout_batch_size:
                    # Keep every selected MRPO group in one optimizer update.
                    # Splitting the group would make later members off-policy
                    # after the first optimizer step.
                    checkpoint = self._update(tuple(pending))
                    pending.clear()
                    updates += 1

        if pending:
            checkpoint = self._update(pending)
            updates += 1

        if self.coverage and checkpoint:
            tasks_by_coverage: dict[str, list[CurriculumTask]] = defaultdict(list)
            for task in tasks:
                tasks_by_coverage[task.coverage_id].append(task)
            for coverage_id, linked_tasks in tasks_by_coverage.items():
                entry = self.coverage.entries.get(coverage_id)
                if not entry or entry.status in {
                    CoverageStatus.NON_ACTIONABLE,
                    CoverageStatus.BLOCKED,
                }:
                    continue
                self.coverage.mark_student_update(coverage_id, checkpoint)
                complete = all(
                    bool(task_profiles[task.task_id])
                    and all(
                        (task.task_id, profile_id) in reviewed_task_profiles
                        for profile_id in task_profiles[task.task_id]
                    )
                    for task in linked_tasks
                )
                if complete:
                    self.coverage.mark_validated(
                        coverage_id,
                        "all linked tasks and selected profiles were teacher-reviewed "
                        "under grouped on-policy rollouts and checkpointed",
                    )

        return DistillationMetrics(
            rollouts=len(rewards),
            updates=updates,
            verified_successes=verified,
            mean_reward=float(np.mean(rewards)) if rewards else 0.0,
            mean_teacher_score=float(np.mean(scores)) if scores else 0.0,
            checkpoint_id=checkpoint,
        )

    def _rollout(
        self,
        task: CurriculumTask,
        profile: EmulatorProfile,
        route: Sequence[str],
    ) -> _Trajectory:
        environment = self.environment_factory(profile)
        rows: list[tuple[object, object, object, object, float]] = []
        observations: list[RolloutObservation] = []
        try:
            observation = environment.reset(task, profile)
            observations.append(observation)
            prefix = completed_prefix_length(route, observations)
            for _ in range(self.config.max_steps_per_task):
                proposal = self.student.propose(task, profile, observation)
                lag = int(self.student.policy_version) - int(proposal.policy_version)
                if lag > self.config.max_policy_lag:
                    raise RuntimeError(f"off-policy rollout rejected: policy lag {lag}")
                outcome = environment.step(proposal)
                judgement = self.teacher.evaluate(
                    task, profile, observation, proposal, outcome
                )
                if judgement.confidence < self.config.min_teacher_confidence:
                    raise RuntimeError(
                        f"teacher confidence {judgement.confidence:.3f} below "
                        f"configured threshold {self.config.min_teacher_confidence:.3f}; "
                        f"teacher={judgement.teacher_id}; tags={judgement.tags}"
                    )

                next_prefix = prefix
                if outcome.verified and route:
                    next_prefix = len(route)
                elif outcome.next_observation is not None:
                    observations.append(outcome.next_observation)
                    next_prefix = completed_prefix_length(route, observations)
                progress_delta = max(0, next_prefix - prefix)
                progress_reward = (
                    self.checkpoint_reward_weight
                    * progress_delta
                    / max(1, len(route))
                )
                reward = (
                    float(outcome.reward)
                    + progress_reward
                    + 0.5 * judgement.total_score
                    + 0.25 * judgement.safety_score
                )
                rows.append((observation, proposal, outcome, judgement, reward))
                prefix = next_prefix
                if outcome.terminal or outcome.next_observation is None:
                    break
                observation = outcome.next_observation

            success = bool(rows and any(row[2].verified for row in rows))
            return _Trajectory(
                rows=tuple(rows),
                observations=tuple(observations),
                terminal_success=success,
                completed_prefix=len(route) if success and route else prefix,
            )
        finally:
            close = getattr(environment, "close", None)
            if callable(close):
                close()

    def _training_rows(
        self, trajectory: _Trajectory, route: Sequence[str]
    ) -> tuple[tuple[tuple[object, object, object, object, float], ...], bool]:
        if not trajectory.rows:
            return (), False
        if trajectory.terminal_success or not route:
            return trajectory.rows, True

        step = last_checkpoint_step(
            route, trajectory.observations, trajectory.completed_prefix
        )
        if step is not None and step > 0:
            return trajectory.rows[:step], True

        # No verified prefix exists. Keep only the final teacher correction for
        # SFT/grounding and disable its policy term instead of learning from an
        # unverified action sequence.
        return (trajectory.rows[-1],), False

    def _mark_review(
        self, task: CurriculumTask, profile: EmulatorProfile, teacher_id: str
    ) -> None:
        if not self.coverage:
            return
        entry = self.coverage.entries.get(task.coverage_id)
        if not entry or entry.status in {
            CoverageStatus.NON_ACTIONABLE,
            CoverageStatus.BLOCKED,
            CoverageStatus.VALIDATED,
        }:
            return
        self.coverage.mark_rollout(task.coverage_id, profile.profile_id)
        self.coverage.mark_teacher_review(task.coverage_id, teacher_id)

    def _update(self, samples: Sequence[DistillationSample]) -> str:
        checkpoint = ""
        for _ in range(self.config.updates_per_batch):
            checkpoint = self.updater.update(samples, self.config)
        return checkpoint

    def _advantages(self, rewards: Sequence[float]) -> tuple[float, ...]:
        returns: list[float] = []
        value = 0.0
        for reward in reversed(rewards):
            value = float(reward) + self.config.gamma * value
            returns.append(value)
        returns.reverse()
        baseline = float(np.mean(returns)) if returns else 0.0
        return tuple(
            float(
                np.clip(
                    value - baseline,
                    -self.config.advantage_clip,
                    self.config.advantage_clip,
                )
            )
            for value in returns
        )


__all__ = ["OnPolicyDistiller"]
